#!/usr/bin/env python3
"""Generate docs/DETECTION_RULES.md (rule reference + detection coverage table) from traceforge/config.py.

CI regenerates it and fails if the committed file differs, so the table can never drift from the code.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "tests"))

from rule_cases import CASES  # noqa: E402

from traceforge.config import DEFAULT_CONFIG, RULES, TACTIC_ORDER  # noqa: E402

OUT = ROOT / "docs" / "DETECTION_RULES.md"
SIGMA_PROOF = "tests/test_redact_sigma_export.py::test_sigma_findings_in_workspace_with_persistence"

NOTES = """## Design notes

- **Burst-based windows.** Events are grouped into bursts separated by less than the window of silence, then tested against the threshold. This keeps evidence lists exact.
- **Spray vs brute force.** A burst touching at least `password_spray.distinct_users` accounts is reported as spraying only, never double-counted as brute force.
- **External means not RFC 1918 / loopback / link-local (IPv6: loopback and fc00::/7).** RFC 5737 documentation ranges used in the sample data therefore count as external.
- **Beaconing** looks at one source host and one external destination and port. It takes the median gap between connections and fires when at least 80% of the gaps are within the configured jitter of that median. It is a rhythm test, not a reputation check, so legitimate update checks and telemetry can match (see the false-positive column).
- **Lateral movement** uses a sliding window over successful logins and counts the distinct destination hosts per source address (or account when there is no address). Remote-execution tooling is matched in command lines separately.
- **Office spawns shell and process rules** need parent and child process information. Windows 4688 and Sysmon event 1 provide it; a CSV without a parent-process column cannot trigger `office_spawns_shell`.
- **Heuristics, not verdicts.** No GeoIP or reputation feeds are used. Every finding lists its evidence event IDs so it can be confirmed or rejected.
- **Imported Sigma rules** run through the same pipeline as built-in rules, so their findings are correlated, redacted, exported and audited the same way. Unsupported constructs are rejected with a reason rather than ignored.

## Adding a rule

1. Write a function `(events, cfg, iocs) -> list[dict]` in `traceforge/detect.py` that returns `_finding(...)` dicts and register it in `RULE_FUNCS`.
2. Add its metadata (including `false_positives` and `remediation`) to `RULES` and its defaults to `DEFAULT_CONFIG` in `traceforge/config.py`; add editable parameters to `PARAMS` if any.
3. Add a minimal data set that makes it fire to `tests/rule_cases.py`, plus a near-miss test in `tests/test_rules.py`. `test_every_rule_has_a_case_and_complete_metadata` fails until you do.
4. Run `python scripts/generate_rule_docs.py` and commit the regenerated file.
"""


def thresholds(rid: str) -> str:
    cfg = {k: v for k, v in DEFAULT_CONFIG.get(rid, {}).items() if k != "enabled"}
    return ", ".join(f"{k}={v}" for k, v in cfg.items()) or "-"


def proof(rid: str) -> str:
    if rid == "sigma_match":
        return f"`{SIGMA_PROOF}`"
    return f"`tests/test_rules.py::test_rule_fires_on_its_case[{rid}]`" if rid in CASES else "**missing**"


def main() -> None:
    order = {t: i for i, t in enumerate(TACTIC_ORDER)}
    ids = sorted(RULES, key=lambda r: (order[RULES[r]["tactic"]], r))
    L = ["# Detection rules and coverage", "",
         "Generated by `scripts/generate_rule_docs.py` from `traceforge/config.py` and `tests/rule_cases.py`; do not edit by hand. "
         "Every threshold can be changed in **Settings** or with `--config` on the CLI.", "",
         "## Detection coverage", "",
         "Each rule, the ATT&CK technique it maps to, the automated test that proves it fires, and where it is known to raise false positives.", "",
         "| Rule | Tactic | ATT&CK | Severity | Default thresholds | Proven by | Known false positives |", "|---|---|---|---|---|---|---|"]
    for rid in ids:
        m = RULES[rid]
        L.append(f"| `{rid}` - {m['name']} | {m['tactic']} | {m['technique']} | {m['severity']} | {thresholds(rid)} | {proof(rid)} | {m['false_positives']} |")
    L += ["", f"{len(ids) - 1} built-in rules plus imported Sigma rules (`sigma_match`).", "", "## What each rule means", ""]
    for rid in ids:
        m = RULES[rid]
        L += [f"### {m['name']} (`{rid}`)", "", m["description"], "", "Suggested response:"] + [f"- {s}" for s in m["remediation"]] + [""]
    L.append(NOTES)
    OUT.write_text("\n".join(L), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(ids)} rules)")


if __name__ == "__main__":
    main()
